/** Reproduce the deployment plugin's self-contained RSS parser from the pinned root dependency. */
import {build} from 'esbuild';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
const root=resolve(import.meta.dirname,'..'), target=resolve(root,'plugins/superagent/src/vendor');
const manifest=JSON.parse(readFileSync(resolve(root,'node_modules/fast-xml-parser/package.json'),'utf8'));
if(manifest.version!=='5.11.1')throw new Error('Regeneration requires fast-xml-parser 5.11.1');
mkdirSync(target,{recursive:true});
await build({stdin:{contents:"export {XMLParser,XMLValidator} from 'fast-xml-parser';",resolveDir:root,sourcefile:'rss-parser-entry.js'},bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,
  outfile:resolve(target,'xml-parser.mjs'),banner:{js:'/* Generated by scripts/vendor-superagent-xml.mjs. fast-xml-parser 5.11.1 and strnum: MIT; see XML-LICENSE.txt. */'},legalComments:'inline'});
const modules=['fast-xml-parser','strnum'];
writeFileSync(resolve(target,'XML-LICENSE.txt'),modules.map(name=>{
  const directory=resolve(root,'node_modules',name),pkg=JSON.parse(readFileSync(resolve(directory,'package.json'),'utf8'));
  return `${name} ${pkg.version}\n\n${readFileSync(resolve(directory,'LICENSE'),'utf8')}`;
}).join('\n\n'));
writeFileSync(resolve(target,'xml-parser.d.mts'),"export {XMLParser, XMLValidator} from 'fast-xml-parser';\n");
