import {createHash} from 'node:crypto';
import {existsSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {join, relative, resolve} from 'node:path';
import {gzipSync} from 'node:zlib';
import yaml from 'js-yaml';

/**
 * Pack each repository plugin in `plugins/` as the npm archive the installer
 * would download, so a deployment offers it without a registry. The archive,
 * its SHA-512 and its patch rows are fixed at build time.
 */
const root = resolve(import.meta.dirname, '..');

/** A deterministic ustar archive of `package/<path>` entries. */
export function packArchive(files) {
  const blocks = [];
  for (const [path, text] of Object.entries(files).sort(([a], [b]) => a.localeCompare(b))) {
    const body = Buffer.from(text), header = Buffer.alloc(512);
    header.write('package/' + path, 0, 100, 'utf8'); header.write('0000644\0', 100); header.write('0000000\0', 108); header.write('0000000\0', 116);
    header.write(body.length.toString(8).padStart(11, '0') + '\0', 124); header.write('00000000000\0', 136); header.fill(32, 148, 156); header.write('0', 156);
    header.write('ustar\0', 257); header.write('00', 263);
    header.write(header.reduce((sum, byte) => sum + byte, 0).toString(8).padStart(6, '0') + '\0 ', 148);
    blocks.push(header, body, Buffer.alloc((512 - body.length % 512) % 512));
  }
  return gzipSync(Buffer.concat([...blocks, Buffer.alloc(1024)]), {level: 9});
}

/** The files npm would publish: the manifest, its `files` entries and README. */
function packageFiles(directory, manifest) {
  const files = {'package.json': readFileSync(join(directory, 'package.json'), 'utf8')};
  const add = path => {
    const full = join(directory, path);
    if (!existsSync(full)) return;
    if (statSync(full).isDirectory()) {for (const name of readdirSync(full)) add(join(path, name)); return;}
    files[relative(directory, full).split('\\').join('/')] = readFileSync(full, 'utf8');
  };
  for (const entry of [...(manifest.files ?? []), 'README.md']) add(entry);
  return files;
}

export function bundledPackages() {
  const plugins = join(root, 'plugins');
  if (!existsSync(plugins)) return [];
  return readdirSync(plugins).sort().flatMap(name => {
    const directory = join(plugins, name);
    if (!existsSync(join(directory, 'package.json'))) return [];
    const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
    if (!manifest.dsh?.bundle?.patch) throw new Error(`${manifest.name} must declare dsh.bundle.patch`);
    if (Object.keys({...manifest.dependencies, ...manifest.peerDependencies}).length) throw new Error(`${manifest.name}: deployment plugins carry no npm dependencies`);
    const archive = packArchive(packageFiles(directory, manifest));
    const integrity = 'sha512-' + createHash('sha512').update(archive).digest('base64');
    const patch = yaml.load(readFileSync(join(directory, manifest.dsh.bundle.patch), 'utf8'), {schema: yaml.JSON_SCHEMA});
    const rows = patch.flatMap(row => row.insert ?? []).map(row => ({rowId: row.id, moduleName: row.name}));
    return [{name: manifest.name, version: manifest.version, description: manifest.description ?? '', rows,
      manifest: {...manifest, dist: {tarball: `weft-bundled:${manifest.name}@${manifest.version}`, integrity}}, archive: archive.toString('base64')}];
  });
}

export function writeBundledPackages(file = join(root, '.generated/bundled-packages.ts')) {
  const packages = bundledPackages();
  writeFileSync(file, `// Generated by scripts/bundled-packages.mjs from plugins/.\nexport const bundledPackages = ${JSON.stringify(packages)} as const;\n`);
  return packages;
}

if (import.meta.url === `file://${process.argv[1]}`) console.log(writeBundledPackages().map(row => `${row.name}@${row.version}`).join('\n'));
