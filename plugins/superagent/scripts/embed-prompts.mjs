import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join, relative, resolve} from 'node:path';

/** Regenerates src/app/prompt-files.ts after an edit under prompts/ or skills/; a test fails when it is stale. */
const root = resolve(import.meta.dirname, '..');
export function promptFiles() {
  const files = {};
  const visit = directory => {
    for (const entry of readdirSync(directory, {withFileTypes: true})) {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) visit(full);
      else if (entry.name.endsWith('.md')) files[relative(join(root, 'prompts'), full).slice(0, -3)] = readFileSync(full, 'utf8');
    }
  };
  visit(join(root, 'prompts'));
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)));
}
export const githubSkill = () => readFileSync(join(root, 'skills/dsh-superagent-github/SKILL.md'), 'utf8');
if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(root, 'src/app/prompt-files.ts'), '/** Generated by plugins/superagent/scripts/embed-prompts.mjs from prompts/ and skills/; a Worker Host has no package files to read. */\n'
    + `export const PROMPT_FILES: Readonly<Record<string, string>> = ${JSON.stringify(promptFiles(), null, 2)}\n`
    + `export const GITHUB_SKILL = ${JSON.stringify(githubSkill())}\n`);
}
