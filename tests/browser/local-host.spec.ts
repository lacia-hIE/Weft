import {test,expect} from '@playwright/test';
import {LOCAL_HOST_BUNDLE} from '../../packages/local-host-connector/compatibility.mjs';
import localHostPackage from '../../packages/local-host-connector/package.json' with {type:'json'};
test('local environment uses native controls for pairing and safe removal',async({page,request,context})=>{
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.goto('/');await page.getByRole('button',{name:'连接本地 DSH',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('0.2.1-rc.2、0.2.1-rc.3');
  await page.getByLabel('环境名称',{exact:true}).fill('My local computer');
  await page.getByRole('button',{name:'生成配对码',exact:true}).click();
  await expect(page.getByRole('button',{name:'下载连接配置',exact:true})).toHaveCount(0);
  const instructions=page.getByRole('dialog').locator('ol');
  await expect(instructions).toContainText('插件 → 添加插件');
  await expect(instructions).toContainText(`${localHostPackage.name}@${localHostPackage.version}`);
  await expect(instructions).toContainText('立即启用');
  await expect(instructions).toContainText('保存并连接');
  await expect(instructions).toContainText('详情页');
  await expect(instructions).toContainText('无需下载文件');
  await expect(page.getByRole('dialog')).toContainText('桌面 App 暂未适配');
  await page.getByRole('button',{name:'复制配对码',exact:true}).click();
  await expect(page.getByRole('button',{name:'已复制配对码',exact:true})).toBeVisible();
  const code=await page.evaluate(()=>navigator.clipboard.readText());
  await expect(page.getByLabel('配对码',{exact:true})).toHaveValue(code);
  const pairing=JSON.parse(Buffer.from(code,'base64url').toString('utf8'));expect(pairing.pairingKey).toMatch(/^[a-f0-9]{64}$/);expect(pairing.endpoint).toContain('/v1/local-hosts/');
  const bundle=page.getByRole('link',{name:'下载本地 Host 插件',exact:true});
  await expect(bundle).toHaveAttribute('href','/downloads/'+LOCAL_HOST_BUNDLE);
  const archive=await request.get((await bundle.getAttribute('href'))!);expect(archive.status()).toBe(200);
  expect([...((await archive.body()).subarray(0,2))]).toEqual([0x1f,0x8b]);
  await page.getByRole('button',{name:'关闭',exact:true}).last().click();
  const card=page.locator('.home-card-frame').filter({hasText:'My local computer'});
  await expect(card).toContainText('等待配对');await expect(card.getByRole('button',{name:'复制',exact:true})).toHaveCount(0);
  const environmentId=await card.locator('.home-card-meta code').innerText();await page.goto('/agents/'+environmentId);await expect(page).toHaveURL('/');await expect(card).toContainText('等待配对');
  await card.getByRole('button',{name:'My local computer 的更多操作'}).click();
  await page.getByRole('menuitem',{name:'删除环境',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('本机的 DSH 数据和进程保留');
  await page.getByLabel('输入环境名称确认删除').fill('My local computer');
  await page.getByRole('button',{name:'删除环境',exact:true}).click();await expect(card).toHaveCount(0);
});

test('the home catalogue pauses polling while hidden and refreshes when visible again',async({page,request})=>{
  const {tenantId}=await(await request.get('/v1/me')).json();
  expect((await request.post(`/v1/tenants/${tenantId}/environments`,{data:{id:'poll-local-'+crypto.randomUUID().slice(0,8),name:'Polling local',kind:'local'}})).status()).toBe(201);
  await page.clock.install();let requests=0;
  page.on('request',request=>{if(request.method()==='GET'&&new URL(request.url()).pathname===`/v1/tenants/${tenantId}/environments`)requests++;});
  await page.goto('/');await expect(page.getByText('Polling local',{exact:true})).toBeVisible();
  const refresh=page.waitForResponse(response=>response.request().method()==='GET'&&new URL(response.url()).pathname===`/v1/tenants/${tenantId}/environments`);
  await page.clock.fastForward(6000);await(await refresh).finished();await expect.poll(()=>requests).toBeGreaterThan(1);
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{value:true,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
  const before=requests;await page.clock.fastForward(30_000);expect(requests).toBe(before);
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{value:false,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
  await expect.poll(()=>requests).toBeGreaterThan(before);
});
