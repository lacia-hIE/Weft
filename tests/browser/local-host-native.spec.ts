import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import localHostPackage from '../../packages/local-host-connector/package.json' with {type:'json'};
test('published local DSH pairs in native settings, runs Files, Git and PTY and recovers through Weft',async({page,request,context},testInfo)=>{
  test.setTimeout(240_000);
  test.skip(process.env.WEFT_LOCAL_DSH_TEST!=='1','Runs in the dedicated native DSH CI job');
  const {base,project,localUrl,pairingCode,bundlePath}=await(await request.get('/__test/local-host')).json() as {base:string;project:string;localUrl:string;pairingCode:string;bundlePath:string};
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  const rpc=async(method:string,args:unknown)=>{
    const result=await(await request.post(base+'/local/web/api/'+method,{data:{type:'client-request',rpcId:crypto.randomUUID(),method,payload:{args}}})).json();
    expect(result.result.ok,JSON.stringify(result)).toBe(true);return result.result.value;
  };
  // Native account and preview notices resolve independently during boot.
  await page.addLocatorHandler(page.getByRole('dialog',{name:'Get started',exact:true}),async dialog=>{await dialog.getByRole('button',{name:'Close',exact:true}).click();});
  await page.addLocatorHandler(page.getByRole('dialog',{name:'Preview Notice',exact:true}),async dialog=>{await dialog.getByRole('button',{name:'Continue',exact:true}).click();});
  await page.goto(localUrl);
  await page.getByRole('button',{name:'Plugins',exact:true}).click({timeout:60_000});
  await page.getByRole('button',{name:'Add plugin',exact:true}).click();
  await page.getByLabel('Package name or address',{exact:true}).fill(bundlePath);
  await page.getByRole('button',{name:'Install',exact:true}).click();
  const installed=page.getByRole('dialog',{name:'Installed',exact:true});
  await expect(installed).toBeVisible({timeout:90_000});
  await installed.getByRole('button',{name:'Enable now',exact:true}).click();
  await expect(page.getByRole('button',{name:'View Weft local connection',exact:true})).toHaveCount(1);
  await page.getByRole('button',{name:'View Weft local connection',exact:true}).click();
  const packageDetail=page.locator(`[data-plugin-detail="${localHostPackage.name}"]`);
  await expect(packageDetail.getByLabel('Pairing code',{exact:true})).toBeVisible();
  const connectionStatus=page.locator('[data-weft-local-connection]').getByRole('status');
  await expect(connectionStatus).toHaveText('Not paired');
  await page.getByLabel('Pairing code',{exact:true}).fill(pairingCode);
  await expect(page.locator('[data-weft-local-connection]')).toContainText('no file download is needed');
  await page.getByRole('button',{name:'Save and connect',exact:true}).click();
  await expect(connectionStatus).toHaveText('Connected',{timeout:45_000});
  await expect(page.getByLabel('Pairing code',{exact:true})).toHaveValue('');
  const panel=page.locator('[data-weft-local-connection]');
  await expect(panel.locator('summary')).toContainText('127.0.0.1:4173');
  await expect(panel.locator('details')).not.toHaveAttribute('open','');
  await expect(panel.getByText(snapshotEndpoint(pairingCode),{exact:true})).toBeHidden();
  await panel.locator('summary').click();
  await expect(panel.getByText(snapshotEndpoint(pairingCode),{exact:true})).toBeVisible();
  await panel.locator('summary').click();
  await page.screenshot({path:testInfo.outputPath('local-dsh-pairing-settings.png')});
  const lightColor=await panel.evaluate(element=>getComputedStyle(element).color);
  await page.emulateMedia({colorScheme:'dark'});
  await expect.poll(()=>panel.evaluate(element=>getComputedStyle(element).color)).not.toBe(lightColor);
  await page.screenshot({path:testInfo.outputPath('local-dsh-pairing-settings-dark.png')});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByLabel('Pairing code',{exact:true})).toBeVisible();
  await expect(panel.getByRole('button',{name:'Save and connect',exact:true})).toBeVisible();
  expect(await panel.evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('local-dsh-pairing-settings-mobile.png')});
  await page.setViewportSize({width:1280,height:720});
  await packageDetail.getByRole('button',{name:'Configure Weft local connection',exact:true}).click();
  await expect(page.getByLabel('Pairing code',{exact:true})).toBeVisible();
  await expect(connectionStatus).toHaveText('Connected');
  const settingsUrl=new URL('/api/weft-local-host',localUrl).href;
  expect((await request.get(settingsUrl)).status()).toBe(401);
  const snapshot=await(await context.request.get(settingsUrl)).json();
  expect(snapshot.state).toBe('connected');expect(JSON.stringify(snapshot)).not.toContain('pairingKey');expect(JSON.stringify(snapshot)).not.toContain('token');
  expect((await context.request.post(settingsUrl,{headers:{origin:'https://untrusted.invalid'},data:{action:'disconnect'}})).status()).toBe(403);
  await page.getByRole('button',{name:'Stop connection',exact:true}).click();await expect(connectionStatus).toHaveText('Connection stopped');
  await page.getByRole('button',{name:'Reconnect',exact:true}).click();await expect(connectionStatus).toHaveText('Connected',{timeout:30_000});
  await rpc('workspace/create',{request:{path:project}});
  const created=await rpc('session/create',{request:{sessionId:crypto.randomUUID(),cwd:project}});const sessionId=created.sessionId;
  await rpc('session/rename',{request:{sessionId,title:'Local browser session'}});
  await page.goto('/agents/native-local-ci');
  await expect(page.getByRole('button',{name:'Plugins',exact:true})).toBeVisible({timeout:60_000});
  expect(page.url()).toContain('/local/web/');
  const release=await page.evaluate(()=>(globalThis as {__DSH_BOOT__?:{release:{version:string}}}).__DSH_BOOT__?.release);
  expect(process.env.WEFT_LOCAL_DSH_VERSION).toBeTruthy();
  expect(release?.version).toBe(process.env.WEFT_LOCAL_DSH_VERSION);
  await page.getByRole('button',{name:'Open right sidebar',exact:true}).click();
  await page.getByRole('button',{name:/New terminal/}).first().click();
  const screen=page.locator('.xterm');await expect(screen).toBeVisible();await screen.click();
  await page.keyboard.type("printf '\\nLOCAL_REAL_PTY_%s\\n' $((20+3))");await page.keyboard.press('Enter');
  await expect(screen).toContainText('LOCAL_REAL_PTY_23',{timeout:30_000});
  await page.keyboard.type("printf '\\nLOCAL_CHANGED_FILE\\n' >> notes.md; git status --porcelain");await page.keyboard.press('Enter');
  await expect(screen).toContainText('M notes.md');
  // Native Files consumes the same on-disk directory used by the terminal.
  await page.getByRole('button',{name:'New tab',exact:true}).click();
  await page.locator('[data-sidebar-right-guide-entry="files"]').click();
  const note=page.locator(`[data-files-path="${project}/notes.md"]`);await expect(note).toBeVisible();await note.getByRole('button').click();
  await expect(page.getByText('LOCAL_CHANGED_FILE',{exact:true})).toBeVisible();
  await page.reload();await expect(page.getByText('LOCAL_CHANGED_FILE',{exact:true})).toBeVisible({timeout:45_000});
  const another=await context.newPage();await another.goto(base+'/local/web/');await expect(another.getByRole('button',{name:'Plugins',exact:true})).toBeVisible({timeout:45_000});await another.close();
  await context.setOffline(true);await page.waitForTimeout(500);await context.setOffline(false);
  await expect.poll(async()=>{try{return(await rpc('session/list',{_request:{}})).items.length;}catch{return 0;}}).toBeGreaterThan(0);
  expect((await request.post('/__test/local-host/restart')).status()).toBe(204);
  await page.reload();
  await expect(page.getByText('LOCAL_CHANGED_FILE',{exact:true})).toBeVisible({timeout:45_000});
  const sessions=await rpc('session/list',{_request:{}});expect(sessions.items.some((row:{sessionId:string})=>row.sessionId===sessionId)).toBe(true);
  expect((await readFile(project+'/notes.md','utf8')).match(/LOCAL_CHANGED_FILE/g)).toHaveLength(1);
  await page.screenshot({path:testInfo.outputPath('local-dsh-native.png')});expect(errors).toEqual([]);
});

function snapshotEndpoint(code:string):string {
  return (JSON.parse(Buffer.from(code,'base64url').toString('utf8')) as {endpoint:string}).endpoint;
}
