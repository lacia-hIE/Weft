import { test, expect } from "@playwright/test";
import {compose} from './compose.ts';

test("Agent catalogue opens the official Harness by default and keeps environment sessions isolated", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", {name: "我的环境"})).toBeVisible();
  await page.getByRole("button", {name: "创建环境", exact: true}).click();
  await page.getByRole("textbox", {name: "环境名称"}).fill("Research environment");
  await page.getByRole("dialog", {name: "创建环境", exact: true}).getByRole("button", {name: "创建环境", exact: true}).click();
  await page.getByRole("link", {name: "进入 Research environment", exact: true}).click();
  await page.getByRole('button', {name: 'Continue', exact: true}).click({timeout: 45_000});
  await expect(page.getByRole('button', {name: 'Select model, current scripted', exact: true})).toBeVisible({timeout: 45_000});
  await compose(page, 'Research environment only');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByText(/^Tenant: /).last()).toBeVisible({timeout: 30_000});
  await page.getByRole('button', {name: 'My environments', exact: true}).click();
  await expect(page).toHaveURL('/');
  await page.getByRole("link", {name: "进入 我的 Harness", exact: true}).click();
  await page.getByRole('button', {name: 'Continue', exact: true}).click({timeout: 45_000});
  await expect(page.getByRole('button', {name: 'Select model, current scripted', exact: true})).toBeVisible({timeout: 45_000});
  await expect(page.getByText('Research environment only', {exact: true})).toHaveCount(0);
  await page.getByRole('button', {name: 'My environments', exact: true}).click();
  await expect(page).toHaveURL('/');
  await page.getByRole('link', {name: '进入 Research environment', exact: true}).click();
  await expect(page.getByText('Research environment only', {exact: true}).last()).toBeVisible({timeout: 45_000});
  expect(errors).toEqual([]);
});


test('environment home shows the authenticated account and uses a native dialog for validated YAML creation', async ({page,request},testInfo)=>{
  const me=await(await request.get('/v1/me')).json() as {user:{email:string};tenantId:string};
  await page.emulateMedia({colorScheme:'dark'});
  await page.setViewportSize({width:1280,height:900});
  await page.goto('/');
  await expect(page.getByText(me.user.email,{exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'我的环境',exact:true})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('environment-home-dark.png')});
  await page.getByRole('button',{name:'创建环境',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'创建环境',exact:true});
  await expect(dialog.getByRole('textbox',{name:'环境名称',exact:true})).toBeFocused();
  await dialog.getByRole('textbox',{name:'环境名称',exact:true}).fill('YAML '+crypto.randomUUID().slice(0,8));
  await dialog.getByRole('button',{name:'使用 YAML 自定义配置（可选）',exact:true}).click();
  const editor=dialog.getByRole('textbox',{name:'初始配置 YAML',exact:true});
  await editor.fill('- id: [');
  await expect(dialog.getByRole('button',{name:'创建环境',exact:true})).toBeDisabled();
  await editor.fill('- id: workspace-runtime\n  config:\n    shell: invalid\n');
  await dialog.getByRole('button',{name:'创建环境',exact:true}).click();
  await expect(dialog.getByRole('alert')).toContainText('环境 YAML 配置无效');
  await expect(editor).toHaveValue(/shell: invalid/);
  await editor.fill('- id: workspace-runtime\n  config:\n    shell: worker\n');
  await page.screenshot({path:testInfo.outputPath('environment-create-yaml-dark.png')});
  const submitted=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/environments')&&response.status()===201);
  await dialog.getByRole('button',{name:'创建环境',exact:true}).click();
  const created=await(await submitted).json() as {id:string;name:string};
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('link',{name:`进入 ${created.name}`,exact:true})).toBeVisible();
  const method='settings/describe';
  const settings=await(await request.post(`/v1/tenants/${me.tenantId}/environments/${created.id}/native/api/${method}`,{data:{type:'client-request',rpcId:crypto.randomUUID(),method,payload:{args:{}}}})).json();
  expect(settings.result.value.namespaces.find((row:{ns:string})=>row.ns==='workspace-runtime').value.shell).toBe('worker');
  await page.emulateMedia({colorScheme:'light'});
  await page.screenshot({path:testInfo.outputPath('environment-home-light.png')});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByText(me.user.email,{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'创建环境',exact:true}).click();
  await expect(dialog.getByRole('textbox',{name:'环境名称',exact:true})).toHaveValue('');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button',{name:'创建环境',exact:true})).toBeFocused();
  await page.screenshot({path:testInfo.outputPath('environment-home-mobile.png')});
});
