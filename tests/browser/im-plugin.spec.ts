import {test, expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('IM setup follows the channel rail, binding, QR and bot card flow with durable settings', async ({page, request}, testInfo) => {
  test.skip(process.env.WEFT_BROWSER_IM !== '1', 'Requires the IM transport and package builder fixture');
  const plugin = JSON.parse(readFileSync('plugins/im/package.json', 'utf8')) as {name: string; version: string};
  const {tenantId} = await (await request.get('/v1/me')).json();
  const environment = 'im-ui-' + crypto.randomUUID().slice(0, 8);
  const base = `/v1/tenants/${tenantId}/environments/${environment}`;
  expect((await request.post(`/v1/tenants/${tenantId}/environments`, {data: {id: environment, name: environment}})).status()).toBe(201);
  const rpc = async (method: string, args: object) => {
    const answer = await (await request.post(`${base}/native/api/${method}`, {data: {type: 'client-request', rpcId: crypto.randomUUID(), method, payload: {args}}})).json();
    expect(answer.result.ok, JSON.stringify(answer)).toBe(true);
    return answer.result.value;
  };
  const settings = async (id: string) => (await rpc('settings/describe', {})).namespaces.find((item: {ns: string}) => item.ns.endsWith('/im-' + id));
  const installed = await rpc('pluginManager/installBundle', {spec: `${plugin.name}@${plugin.version}`, options: {requestId: crypto.randomUUID()}});
  expect(installed.application).toBe('applied');
  const row = (await (await request.get(base + '/native/package-installations')).json()).installations[0];
  expect(row.permissions.client).toBe(true);
  expect((await request.post(base + '/native/package-installations', {data: {operation: 'approve', name: row.name, digest: row.digest, permissions: row.permissions}})).status()).toBe(200);
  const open = async () => {
    await expect(page.getByRole('treeitem', {name: /New Session/}).first()).toBeVisible({timeout: 45_000});
    await page.getByRole('button', {name: 'Settings', exact: true}).click({timeout: 45_000});
    await page.getByRole('button', {name: 'IM bots', exact: true}).click();
  };
  await page.setViewportSize({width: 1440, height: 1000});
  await page.goto('/agents/' + environment);
  await page.getByRole('button', {name: 'Continue', exact: true}).click({timeout: 45_000});
  await open();
  const panel = page.getByRole('region', {name: 'IM bots', exact: true});
  const navigation = panel.getByRole('tablist', {name: 'IM settings navigation', exact: true});
  await expect(panel.getByText('DSH-IM', {exact: true})).toBeVisible();
  await expect(panel.getByRole('tabpanel', {name: 'WeChat', exact: true}).getByText('No bots connected', {exact: true})).toBeVisible();
  await expect(navigation.getByRole('tab', {name: 'WeChat', exact: true})).toHaveAttribute('aria-selected', 'true');
  await navigation.getByRole('tab', {name: 'WeChat', exact: true}).focus();
  await page.keyboard.press('ArrowDown');
  await expect(navigation.getByRole('tab', {name: 'Feishu', exact: true})).toBeFocused();
  const feishu = panel.getByRole('tabpanel', {name: 'Feishu', exact: true});
  const railBox = await navigation.boundingBox(), bodyBox = await feishu.boundingBox();
  expect(railBox!.x + railBox!.width).toBeLessThan(bodyBox!.x);
  await feishu.getByRole('button', {name: 'Manual setup', exact: true}).first().click();
  await expect(feishu.getByLabel('Callback URL')).toHaveValue(new RegExp(`/v1/plugin-hooks/${tenantId}/${environment}/${encodeURIComponent(plugin.name)}/feishu$`));
  await feishu.getByLabel('App ID', {exact: true}).fill('cli_browser');
  await feishu.getByRole('button', {name: 'Bind bot', exact: true}).click();
  await expect(feishu.getByRole('alert')).toHaveText('Enter App ID and App Secret; Feishu also requires Verification Token.');
  await feishu.getByLabel('App Secret', {exact: true}).fill('browser-secret');
  await feishu.getByLabel('Verification Token', {exact: true}).fill('browser-verify');
  // Each channel retains its in-progress form while moving through the rail.
  await navigation.getByRole('tab', {name: 'QQ', exact: true}).click();
  await navigation.getByRole('tab', {name: 'Feishu', exact: true}).click();
  await expect(feishu.getByLabel('App ID', {exact: true})).toHaveValue('cli_browser');
  await feishu.getByRole('button', {name: 'Bind bot', exact: true}).click();
  await expect(feishu.getByRole('article', {name: 'Feishu', exact: true})).toBeVisible();
  await feishu.getByRole('button', {name: 'More settings', exact: true}).click();
  await feishu.getByLabel('Bot alias', {exact: true}).fill('Team bot');
  await feishu.getByLabel('Workspace', {exact: true}).fill('/workspace/team');
  await feishu.getByRole('button', {name: 'Save configuration', exact: true}).click();
  await expect(feishu.getByText('Configuration saved', {exact: true})).toBeVisible();
  await feishu.getByRole('tab', {name: 'Access', exact: true}).click();
  await feishu.getByLabel('Allowed user IDs', {exact: true}).fill('ou_browser\n');
  await feishu.getByRole('button', {name: 'Save configuration', exact: true}).click();
  await expect(feishu.getByText('Configuration saved', {exact: true})).toBeVisible();
  let form = await settings('feishu');
  expect(form.value.allowedSenders).toEqual(['ou_browser']);
  expect(form.value.workspace).toBe('/workspace/team');
  expect(form.value.displayName).toBe('Team bot');
  expect(form.secrets.find((item: {path: string[]}) => item.path[0] === 'appSecret').set).toBe(true);
  expect(JSON.stringify(form)).not.toContain('browser-secret');
  await feishu.getByRole('button', {name: 'Back to bot list', exact: true}).click();
  await feishu.getByRole('button', {name: 'Check connection', exact: true}).click();
  await expect(feishu.getByText('Credentials verified', {exact: true})).toBeVisible();
  await feishu.getByRole('button', {name: 'Manual setup', exact: true}).click();
  await expect(feishu.getByLabel('App Secret', {exact: true})).toHaveValue('');
  await feishu.getByLabel('App ID', {exact: true}).fill('cli_browser_updated');
  await feishu.getByRole('button', {name: 'Bind bot', exact: true}).click();
  form = await settings('feishu');
  expect(form.value.appId).toBe('cli_browser_updated');
  expect(form.secrets.find((item: {path: string[]}) => item.path[0] === 'appSecret').set).toBe(true);
  // A provider error cannot echo a secret into the UI or claim a healthy connection.
  await feishu.getByRole('button', {name: 'Manual setup', exact: true}).click();
  await feishu.getByLabel('App Secret', {exact: true}).fill('invalid-fixture');
  await feishu.getByRole('button', {name: 'Bind bot', exact: true}).click();
  await feishu.getByRole('button', {name: 'Check connection', exact: true}).click();
  await expect(feishu.getByRole('alert')).toHaveText('Credential verification failed. Check the app credentials and network connection, then retry.');
  await expect(feishu.getByText('Connection error', {exact: true})).toBeVisible();
  await expect(feishu.getByText('invalid-fixture', {exact: false})).toHaveCount(0);
  await navigation.getByRole('tab', {name: 'QQ', exact: true}).click();
  const qq = panel.getByRole('tabpanel', {name: 'QQ', exact: true});
  await qq.getByRole('button', {name: 'Manual setup', exact: true}).first().click();
  await expect(qq.getByLabel('Callback URL')).toHaveValue(new RegExp(`/${environment}/${encodeURIComponent(plugin.name)}/qq$`));
  await qq.getByLabel('App ID', {exact: true}).fill('102030');
  await qq.getByLabel('App Secret', {exact: true}).fill('qq-secret');
  await qq.getByRole('button', {name: 'Bind bot', exact: true}).click();
  await qq.getByRole('button', {name: 'Check connection', exact: true}).click();
  await expect(qq.getByText('Credentials verified', {exact: true})).toBeVisible();
  await qq.getByRole('button', {name: 'Pause', exact: true}).click();
  await expect(qq.getByText('Paused', {exact: true})).toBeVisible();
  await qq.getByRole('button', {name: 'Resume', exact: true}).click();
  await expect(qq.getByText('Not checked yet', {exact: true})).toBeVisible();
  await navigation.getByRole('tab', {name: 'WeChat', exact: true}).click();
  const wechat = panel.getByRole('tabpanel', {name: 'WeChat', exact: true});
  await wechat.getByRole('button', {name: 'Connect with QR', exact: true}).first().click();
  const qr = wechat.getByRole('img', {name: 'WeChat login QR code', exact: true});
  await expect(qr.locator('svg')).toBeVisible({timeout: 20_000});
  await expect(wechat.getByText('Open WeChat and scan this code', {exact: true})).toBeVisible();
  await qr.scrollIntoViewIfNeeded();
  await page.screenshot({path: testInfo.outputPath('im-reference-qr.png')});
  await page.route('**/weixin/status', async route => {
    expect(route.request().headers().authorization).toMatch(/^Bearer /);
    expect(route.request().url()).not.toContain('?key=');
    await route.fulfill({json: {state: 'idle', error: 'QR expired fixture'}});
  });
  await expect(wechat.getByRole('alert')).toHaveText('QR expired fixture');
  await expect(qr).toHaveCount(0);
  await expect(wechat.getByText('QR code expired\nGet a new code', {exact: true})).toBeVisible();
  await wechat.getByRole('button', {name: 'Refresh QR code', exact: true}).click();
  await expect(qr.locator('svg')).toBeVisible();
  await page.unroute('**/weixin/status');
  await page.route('**/weixin/status', route => route.fulfill({json: {state: 'online', botId: 'browser-bot', owner: 'browser-owner'}}));
  await expect(wechat.getByText('Running normally', {exact: true})).toBeVisible();
  await expect(qr).toHaveCount(0);
  await expect(wechat.getByRole('article', {name: 'WeChat', exact: true})).toBeVisible();
  await page.screenshot({path: testInfo.outputPath('im-reference-bot-card.png')});
  await page.reload();
  await open();
  await navigation.getByRole('tab', {name: 'Feishu', exact: true}).click();
  await expect(feishu.getByRole('article', {name: 'Team bot', exact: true})).toBeVisible();
  await expect(feishu.getByText('/workspace/team', {exact: true})).toBeVisible();
  await navigation.getByRole('tab', {name: 'QQ', exact: true}).click();
  await qq.getByRole('button', {name: 'Remove bot', exact: true}).click();
  await qq.getByRole('button', {name: 'Confirm removal', exact: true}).click();
  await expect(qq.getByText('No bots connected', {exact: true})).toBeVisible();
  expect((await settings('qq')).value.enabled).toBe(false);
  await navigation.getByRole('tab', {name: 'WeChat', exact: true}).click();
  await wechat.getByRole('button', {name: 'Remove bot', exact: true}).click();
  await wechat.getByRole('button', {name: 'Keep bot', exact: true}).click();
  await expect(wechat.getByRole('article')).toBeVisible();
  await wechat.getByRole('button', {name: 'Remove bot', exact: true}).click();
  await wechat.getByRole('button', {name: 'Confirm removal', exact: true}).click();
  await expect(wechat.getByText('No bots connected', {exact: true})).toBeVisible();
  expect((await settings('weixin')).value.accountConfigured).toBe(false);
  await panel.getByRole('button', {name: 'General settings', exact: true}).click();
  await panel.getByLabel('Prefix session titles with the channel', {exact: true}).uncheck();
  await panel.getByRole('button', {name: 'Save configuration', exact: true}).click();
  await expect(panel.getByRole('region', {name: 'General settings', exact: true}).getByText('Configuration saved', {exact: true})).toBeVisible();
  expect((await settings('core')).value.titlePrefix).toBe(false);
  await page.setViewportSize({width: 430, height: 900});
  await navigation.getByRole('tab', {name: 'Feishu', exact: true}).click();
  await expect(feishu.getByRole('article', {name: 'Team bot', exact: true})).toBeVisible();
  const bounds = await panel.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(430);
  expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({path: testInfo.outputPath('im-reference-mobile.png')});
  await rpc('pluginManager/setBundleEnabled', {name: plugin.name, enabled: false});
  await expect(page.getByRole('button', {name: 'IM bots', exact: true})).toHaveCount(0);
  await expect(page.locator('link[data-plugin-css="' + row.digest + '"]')).toHaveCount(0);
});

test('IM conversations show channel logos and readable native titles in the tree and search, and restore on unload', async ({page, request}, testInfo) => {
  test.skip(process.env.WEFT_BROWSER_IM !== '1', 'Requires the IM package builder fixture');
  const plugin = JSON.parse(readFileSync('plugins/im/package.json', 'utf8')) as {name: string; version: string};
  const {tenantId} = await (await request.get('/v1/me')).json();
  const environment = 'im-titles-' + crypto.randomUUID().slice(0, 8);
  const base = `/v1/tenants/${tenantId}/environments/${environment}`;
  expect((await request.post(`/v1/tenants/${tenantId}/environments`, {data: {id: environment, name: environment}})).status()).toBe(201);
  const rpc = async (method: string, args: object) => {
    const answer = await (await request.post(`${base}/native/api/${method}`, {data: {type: 'client-request', rpcId: crypto.randomUUID(), method, payload: {args}}})).json();
    expect(answer.result.ok, JSON.stringify(answer)).toBe(true);
    return answer.result.value;
  };
  await rpc('pluginManager/installBundle', {spec: `${plugin.name}@${plugin.version}`, options: {requestId: crypto.randomUUID()}});
  const installation = (await (await request.get(base + '/native/package-installations')).json()).installations[0];
  expect((await request.post(base + '/native/package-installations', {data: {operation: 'approve', name: installation.name, digest: installation.digest, permissions: installation.permissions}})).status()).toBe(200);
  const sessions: {channel: string; label: string; id: string}[] = [];
  for (const [channel, label] of [['weixin', '微信'], ['feishu', '飞书'], ['qq', 'QQ']]) {
    const {sessionId} = await rpc('session/create', {request: {}});
    sessions.push({channel: channel!, label: label!, id: sessionId});
    await rpc('session/prompt', {request: {sessionId, requestId: `${channel}-${crypto.randomUUID()}`, mode: 'queue', content: [{type: 'text', text: 'Plan channel-logo-regression milestones'}]}});
  }
  await expect(async () => {
    const list = (await rpc('session/list', {_request: {}})).items;
    for (const session of sessions) {
      const row = list.find((item: {sessionId: string}) => item.sessionId === session.id);
      expect(row).toMatchObject({blank: false, running: false});
      expect(row.projections.values.title).toMatch(new RegExp(`^${session.label} · `));
    }
  }).toPass({timeout: 45_000});
  for (const session of sessions) await rpc('session/rename', {request: {sessionId: session.id, title: 'Quarterly milestones'}});
  const legacy = (await rpc('session/create', {request: {}})).sessionId;
  await rpc('session/prompt', {request: {sessionId: legacy, requestId: crypto.randomUUID(), mode: 'queue', content: [{type: 'text', text: 'Legacy channel conversation'}]}});
  await expect(async () => expect((await rpc('session/list', {_request: {}})).items.find((item: {sessionId: string}) => item.sessionId === legacy).running).toBe(false)).toPass({timeout: 30_000});
  await rpc('session/rename', {request: {sessionId: legacy, title: '[weixin] Legacy contact'}});
  const ordinary = (await rpc('session/create', {request: {}})).sessionId;
  await rpc('session/prompt', {request: {sessionId: ordinary, requestId: crypto.randomUUID(), mode: 'queue', content: [{type: 'text', text: 'Discuss 微信 · ordinary Web session'}]}});
  await page.setViewportSize({width: 1440, height: 1000});
  await page.goto('/agents/' + environment);
  await page.getByRole('button', {name: 'Continue', exact: true}).click({timeout: 45_000});
  const marked = '[data-weft-im-session-channel]';
  for (const session of sessions) {
    const row = page.locator(`[data-row-key="session:${session.id}"]`);
    const title = row.locator(marked);
    await expect(title).toHaveAttribute('data-weft-im-session-channel', session.channel, {timeout: 45_000});
    await expect(title).toHaveAttribute('data-weft-im-session-text', 'Quarterly milestones');
    // Preserve React's text node and accessible channel name; the loaded logo
    // and clipped visual text come from plugin-owned CSS pseudo-elements.
    await expect(title).toHaveText(`${session.label} · Quarterly milestones`);
    const style = await title.evaluate(element => ({before: getComputedStyle(element, '::before').backgroundImage, after: getComputedStyle(element, '::after').content}));
    expect(style.before).toContain('data:image/svg+xml');
    expect(style.after).toContain('Quarterly milestones');
  }
  await expect(page.locator(`[data-row-key="session:${legacy}"]`).locator(marked)).toHaveAttribute('data-weft-im-session-channel', 'weixin');
  await expect(page.locator(`[data-row-key="session:${ordinary}"]`).locator(marked)).toHaveCount(0);
  await page.screenshot({path: testInfo.outputPath('im-session-logos.png')});
  // The native rename dialog receives the full persisted title and remains usable.
  const feishu = page.locator(`[data-row-key="session:${sessions[1]!.id}"]`);
  await feishu.locator(marked).click();
  await feishu.locator(marked).dblclick();
  const dialog = page.getByRole('dialog', {name: 'Rename session', exact: true});
  await expect(dialog).toBeVisible();
  await dialog.getByRole('textbox').fill('Updated roadmap');
  await dialog.getByRole('button', {name: 'Rename', exact: true}).click();
  await expect(feishu.locator(marked)).toHaveAttribute('data-weft-im-session-text', 'Updated roadmap');
  await page.getByRole('button', {name: 'Search sessions', exact: true}).click();
  await page.getByPlaceholder('Search session names', {exact: true}).fill('channel-logo-regression');
  const results = page.getByRole('tree', {name: 'Search results', exact: true});
  await expect(results.getByRole('treeitem')).toHaveCount(3, {timeout: 45_000});
  for (const session of sessions) await expect(results.locator(`[data-weft-im-session-channel="${session.channel}"]`)).toHaveCount(1);
  await rpc('pluginManager/setBundleEnabled', {name: plugin.name, enabled: false});
  await expect(page.locator(marked)).toHaveCount(0);
  await expect(page.locator('style[data-plugin-css="weft-im-session-channel-logos"]')).toHaveCount(0);
  await expect(results.getByText('飞书 · Updated roadmap', {exact: true})).toBeVisible();
  await rpc('pluginManager/setBundleEnabled', {name: plugin.name, enabled: true});
  await expect(results.locator(marked)).toHaveCount(3);
  await page.reload();
  await expect(page.locator(`[data-row-key="session:${sessions[1]!.id}"]`).locator(marked)).toHaveAttribute('data-weft-im-session-text', 'Updated roadmap', {timeout: 45_000});
});
